struct pod_row {
    const char *name; /* row widget name in the asset (pod_row0, pod_row1, ...) */
    int action; /* ACT_* */
    int arg; /* HOME_* id, or a page index */
};

struct pod_page {
    const char *asset; /* window resource name (ui/<asset>.bin) */
    const struct pod_row *rows;
    int count;
};

